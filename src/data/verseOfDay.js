/** Le passage du jour pour une date donnée (cycle sur le jour de l'année). */
export function verseRefForDate(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0)
  const diff = date - start
  const dayOfYear = Math.floor(diff / 86400000) // 1..366
  return POOL[(dayOfYear - 1) % POOL.length]
}

export function todayRef() {
  return verseRefForDate(new Date())
}
